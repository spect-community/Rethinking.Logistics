#!/usr/bin/env node
// Applies curation results (Phase 3) to insight notes and writes import/curation-log.md.
//
// Input: import/private/curation/<batch>.json — see import/private/curation/BRIEF.md:
//   { "batch": "01", "entries": { "<insight note name>": {
//       "challenges": [{ "name", "why" }], "metrics": [...], "case_studies": [...],
//       "relevance": 1|2|3, "no_link": "...", "flag": { "reason": "..." } } } }
//
// Writes `challenges`, `metrics`, `case_studies` and `relevance` into each insight's
// frontmatter (in content/Insights/ or import/private/held-insights/). A flag sets
// `evidence_status: disputed` and adds "## What needs checking (curation)". Links to
// names that are not existing notes of the right type are refused and reported.
// Statements are never touched. Safe to run again.
//
// Usage: node scripts/apply-curation.mjs [batch ...]   (default: all batch files)

import fs from "node:fs"
import path from "node:path"
import { ROOT, CONTENT, loadKB, key } from "./lib/kb.mjs"

const DIR = path.join(ROOT, "import", "private", "curation")
const FOLDERS = [path.join(CONTENT, "Insights"), path.join(ROOT, "import", "private", "held-insights")]
const LOG = path.join(ROOT, "import", "curation-log.md")
const FIELDS = { challenges: "challenge", metrics: "metric", case_studies: "case-study" }

const kb = loadKB()
const only = process.argv.slice(2)
const all = fs.readdirSync(DIR).filter((f) => f.endsWith(".json")).sort()
const files = all.filter((f) => !only.length || only.includes(f.replace(/\.json$/, "")))
const problems = []
let updated = 0

const yamlList = (k, names) => (names.length ? `${k}:\n${names.map((n) => `  - "[[${n}]]"`).join("\n")}` : `${k}: []`)
const setField = (fm, k, block) => {
  const re = new RegExp(`^${k}:(?: \\[\\])?[^\\n]*\\n?((?:  - .*\\n?)*)`, "m")
  return re.test(fm) ? fm.replace(re, block + "\n") : fm.replace(/\n*$/, "\n" + block + "\n")
}

for (const file of files) {
  const data = JSON.parse(fs.readFileSync(path.join(DIR, file), "utf8"))
  for (const [name, e] of Object.entries(data.entries)) {
    const target = FOLDERS.map((d) => path.join(d, `${name}.md`)).find((p) => fs.existsSync(p))
    if (!target) { problems.push(`${file}: no insight note "${name}"`); continue }
    const raw = fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n")
    const m = raw.match(/^---\n([\s\S]*?)\n---\n?/)
    let fm = m[1] + "\n"
    let body = raw.slice(m[0].length)
    for (const [field, type] of Object.entries(FIELDS)) {
      const names = []
      for (const l of e[field] ?? []) {
        const note = kb.find(l.name)
        if (!note || note.type !== type) { problems.push(`${file}: "${name}" → ${field} "${l.name}" is not an existing ${type}`); continue }
        if (!names.includes(note.name)) names.push(note.name)
      }
      fm = setField(fm, field, yamlList(field, names))
    }
    if (e.relevance) {
      fm = /^relevance:/m.test(fm) ? fm.replace(/^relevance:.*$/m, `relevance: ${e.relevance}`) : fm.replace(/^(reviewed_by:.*)$/m, `$1\nrelevance: ${e.relevance}`)
    }
    body = body.replace(/\n## What needs checking \(curation\)\n[\s\S]*?(?=\n## |$)/, "")
    if (e.flag?.reason) {
      fm = fm.replace(/^evidence_status:.*$/m, "evidence_status: disputed")
      body = body.trimEnd() + `\n\n## What needs checking (curation)\n\n${e.flag.reason.trim()}\n`
    }
    fs.writeFileSync(target, `---\n${fm.replace(/\n+$/, "")}\n---\n${body.replace(/^\n*/, "")}`)
    updated++
  }
}

// curation log, rebuilt from all batch files
let log = `# Curation log — insights\n\nGenerated by \`scripts/apply-curation.mjs\` from \`import/private/curation/*.json\`. One line per link with its justification. Held-back (sensitive) insights are marked † and their titles are not shown.\n`
const held = new Set(fs.existsSync(FOLDERS[1]) ? fs.readdirSync(FOLDERS[1]).map((f) => f.replace(/\.md$/, "")) : [])
for (const file of all) {
  const data = JSON.parse(fs.readFileSync(path.join(DIR, file), "utf8"))
  const es = Object.entries(data.entries)
  const rel = [3, 2, 1].map((r) => es.filter(([, e]) => e.relevance === r).length)
  log += `\n## Batch ${data.batch}\n\n${es.length} insights · relevance 3/2/1: ${rel.join("/")} · with links: ${es.filter(([, e]) => Object.keys(FIELDS).some((f) => (e[f] ?? []).length)).length} · flagged: ${es.filter(([, e]) => e.flag?.reason).length}\n\n`
  for (const [name, e] of es) {
    const title = held.has(name) ? "† held-back insight (title not shown)" : `[[${name}]]`
    log += `- **${title}** — relevance ${e.relevance ?? "?"}\n`
    for (const f of Object.keys(FIELDS)) for (const l of e[f] ?? []) log += `  - ${f.replace("_", " ")}: ${l.name} — ${l.why}\n`
    if (e.no_link) log += `  - no link: ${e.no_link}\n`
    if (e.flag?.reason) log += `  - flagged: ${e.flag.reason}\n`
  }
}
fs.writeFileSync(LOG, log)

console.log(`Updated ${updated} insights from ${files.length} batch file(s); log: import/curation-log.md`)
if (problems.length) { console.log(`Problems (${problems.length}):`); for (const p of problems) console.log("  - " + p) }
